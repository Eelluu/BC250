#!/usr/bin/env bash
# bc250-cu-health-test.sh - reboot-resuming per-WGP health test for BC-250.

set -euo pipefail

STATEDIR="${BC250_CU_HEALTH_STATE:-/var/lib/bc250-cu-health-test}"
CONF="${BC250_CU_HEALTH_CONF:-/etc/modprobe.d/bc250-cu-health-isolate.conf}"
SERVICE="${BC250_CU_HEALTH_SERVICE:-bc250-cu-health-resume.service}"
VERIFY="${BC250_CU_VERIFY:-$(dirname "$(readlink -f "$0")")/bc250-compute-verify.sh}"
ELEMENTS="${BC250_CU_HEALTH_ELEMENTS:-16777216}"
PASSES="${BC250_CU_HEALTH_PASSES:-2}"
ITERS="${BC250_CU_HEALTH_ITERS:-64}"
REBOOT_DELAY="${BC250_CU_HEALTH_REBOOT_DELAY:-5}"
FINAL_REBOOT="${BC250_CU_HEALTH_FINAL_REBOOT:-1}"
TIMEOUT="${BC250_CU_HEALTH_TIMEOUT:-120}"
GRUB_CFG="${BC250_CU_HEALTH_GRUB_CFG:-/boot/grub/grub.cfg}"
GRUB_BACKUP="${GRUB_CFG}.bc250-health-backup"
GRUB_MARKER="#BC250_HEALTH_MARKER"

usage() {
	cat <<EOF
Usage: $0 direct|start|resume|quick|status|reset

Commands:
  direct  Test all 20 WGPs in one session via hot-reload (no reboots).
          Recommended for Alpine or any distro where amdgpu can be unloaded.
  start   Install a resume service (systemd or OpenRC) and test all 20 WGPs
          across reboots. Use when hot-reload is not possible.
  resume  Internal command used by the resume service after each reboot.
  quick   Run the heavy verifier once in the current CU configuration.
  status  Print saved progress/results.
  reset   Remove state, resume service, and isolation config.

Environment:
  BC250_CU_HEALTH_ELEMENTS=$ELEMENTS
  BC250_CU_HEALTH_PASSES=$PASSES
  BC250_CU_HEALTH_ITERS=$ITERS
  BC250_CU_HEALTH_FINAL_REBOOT=$FINAL_REBOOT
  BC250_CU_HEALTH_TIMEOUT=$TIMEOUT

Results:
  $STATEDIR/results.tsv
EOF
}

die() {
	echo "ERROR: $*" >&2
	exit 1
}

is_alpine() {
	[ -f /etc/alpine-release ]
}

is_alpine_grub() {
	is_alpine && [ -f /boot/grub/grub.cfg ]
}

# ---------------------------------------------------------------------------
# GRUB kernel cmdline helpers (Alpine): edit amdgpu.disable_cu= on the
# kernel command line so the GPU boots directly with the right isolation.
# This avoids modprobe -r (which freezes the kernel on some BC-250 GPUs),
# initramfs rebuilds, and modprobe.d config files.
# ---------------------------------------------------------------------------
grub_init_cmdline() {
	if [ ! -f "$GRUB_CFG" ]; then
		die "GRUB config not found at $GRUB_CFG"
	fi
	# Safety: don't double-init
	if grep -qF "$GRUB_MARKER" "$GRUB_CFG" 2>/dev/null; then
		echo "GRUB already initialised for health test (marker found)."
		return 0
	fi
	cp "$GRUB_CFG" "$GRUB_BACKUP"
	local lineno
	lineno=$(grep -nE '^\s*linux\s' "$GRUB_CFG" | head -1 | cut -d: -f1)
	[ -n "$lineno" ] || die "No 'linux' line found in $GRUB_CFG"
	sed -i "${lineno}s/$/ amdgpu.bc250_cc_write_mode=3 $GRUB_MARKER/" "$GRUB_CFG"
	echo "GRUB: initialised — backup saved to $GRUB_BACKUP"
}

grub_set_disable_cu() {
	local disable_csv="$1"
	if grep -q 'amdgpu\.disable_cu=' "$GRUB_CFG"; then
		sed -i "s/amdgpu\.disable_cu=[^ #]*/amdgpu.disable_cu=$disable_csv/" "$GRUB_CFG"
	else
		# First time: insert before the marker
		sed -i "s/ $GRUB_MARKER/ amdgpu.disable_cu=$disable_csv $GRUB_MARKER/" "$GRUB_CFG"
	fi
	echo "GRUB: set disable_cu=$disable_csv"
}

grub_restore() {
	if [ -f "$GRUB_BACKUP" ]; then
		cp "$GRUB_BACKUP" "$GRUB_CFG"
		rm -f "$GRUB_BACKUP"
		echo "GRUB: restored original $GRUB_CFG"
	else
		echo "GRUB: no backup at $GRUB_BACKUP — nothing to restore" >&2
	fi
}

need_root() {
	[ "$(id -u)" = "0" ] || die "must run as root"
}

target_to_tuple() {
	local idx="$1"
	local se sh wgp

	se=$((idx / 10))
	sh=$(((idx / 5) % 2))
	wgp=$((idx % 5))
	echo "$se $sh $wgp"
}

disable_cu_for_target() {
	local target="$1"
	local out=()
	local idx se sh wgp tse tsh twgp cu

	read -r tse tsh twgp < <(target_to_tuple "$target")
	for idx in $(seq 0 19); do
		read -r se sh wgp < <(target_to_tuple "$idx")
		if [ "$se" -eq "$tse" ] && [ "$sh" -eq "$tsh" ] && [ "$wgp" -eq "$twgp" ]; then
			continue
		fi
		out+=("$se.$sh.$((wgp * 2))")
		out+=("$se.$sh.$((wgp * 2 + 1))")
	done
	IFS=,
	echo "${out[*]}"
}

write_config_for_target() {
	local target="$1"
	local disable_csv
	local se sh wgp

	read -r se sh wgp < <(target_to_tuple "$target")
	disable_csv="$(disable_cu_for_target "$target")"
	cat >"$CONF" <<EOF
# BC-250 per-WGP health-test isolation config.
# Target: index=$target SE$se SH$sh WGP$wgp CUs $((wgp * 2))-$((wgp * 2 + 1)).
# Generated by $0 on $(date -Iseconds).
options amdgpu bc250_cc_write_mode=3 disable_cu=$disable_csv
EOF
}

write_full_config() {
	cat >"$CONF" <<EOF
# BC-250 full 40-CU config restored after health test.
options amdgpu bc250_cc_write_mode=3
EOF
}

refresh_initramfs() {
	if command -v mkinitfs >/dev/null 2>&1; then
		mkinitfs -k "$(uname -r)" || true
	elif command -v mkinitcpio >/dev/null 2>&1; then
		mkinitcpio -P || true
	elif command -v update-initramfs >/dev/null 2>&1; then
		update-initramfs -u -k "$(uname -r)" || true
	elif command -v dracut >/dev/null 2>&1; then
		dracut -f || true
	fi
}

# On Alpine, mkinitfs bakes /etc/modprobe.d/ into the initramfs.
# We must NOT rebuild initramfs during per-WGP iterations.
# Instead, hot-reload amdgpu after each config change:
#   1. Apply isolation → reload → test
#   2. Restore 40 CUs → reload → reboot (next boot is clean)
hot_reload_amdgpu() {
	local reason="${1:-config change}"
	local disable_csv="${2:-}"
	echo "Hot-reloading amdgpu ($reason)..."
	set +e
	# Kill userspace processes holding DRM devices (e.g. GPU governor daemons)
	# otherwise modprobe -r will fail with "Module amdgpu is in use"
	fuser -k /dev/dri/renderD128 2>/dev/null || true
	fuser -k /dev/dri/card0 2>/dev/null || true
	sleep 1
	if ! modprobe -r amdgpu 2>/dev/null; then
		echo "WARNING: modprobe -r failed — trying rmmod." >&2
		rmmod amdgpu 2>/dev/null || true
	fi
	# Check if we actually managed to unload
	if lsmod 2>/dev/null | grep -q '^amdgpu '; then
		echo "FATAL: Cannot unload amdgpu — module still in use." >&2
		echo "Isolation will NOT be applied. Skipping reload." >&2
		set -e
		return 1
	fi
	sleep 2
	if [ -n "$disable_csv" ]; then
		# Pass parameters inline: busybox modprobe may not read modprobe.d
		modprobe amdgpu bc250_cc_write_mode=3 "disable_cu=$disable_csv" 2>/dev/null || true
	else
		modprobe amdgpu bc250_cc_write_mode=3 2>/dev/null || true
	fi
	set -e
	sleep 2
	local cu_after
	cu_after=$(current_cu_count || echo '?')
	echo "amdgpu reloaded. Active CUs: $cu_after."
	# Verify isolation actually took effect
	if [ -n "$disable_csv" ] && [ "$cu_after" != "2" ]; then
		echo "ERROR: Isolation FAILED: expected 2 active CUs, got $cu_after." >&2
		return 1
	fi
}

install_service() {
	local self

	self="$(readlink -f "$0")"

	if command -v systemctl >/dev/null 2>&1; then
		# systemd (Debian, Fedora, Arch, Alpine with systemd)
		cat >/etc/systemd/system/"$SERVICE" <<EOF
[Unit]
Description=Resume BC-250 per-WGP CU health test
After=multi-user.target

[Service]
Type=oneshot
ExecStart=/bin/bash $self resume
StandardOutput=journal+console
StandardError=journal+console

[Install]
WantedBy=multi-user.target
EOF
		systemctl daemon-reload
		systemctl enable "$SERVICE"
	elif command -v rc-update >/dev/null 2>&1; then
		# OpenRC (Alpine default)
		mkdir -p /etc/local.d
		cat >/etc/local.d/"${SERVICE}".start <<EOF
#!/bin/sh
# BC-250 per-WGP CU health test resume script (OpenRC local.d)
/bin/bash $self resume
EOF
		chmod +x /etc/local.d/"${SERVICE}".start
		rc-update add local default 2>/dev/null || true
		echo "OpenRC: installed /etc/local.d/${SERVICE}.start"
	else
		die "Neither systemd nor OpenRC found. Cannot install resume service."
	fi
}

remove_service() {
	if command -v systemctl >/dev/null 2>&1; then
		systemctl disable "$SERVICE" >/dev/null 2>&1 || true
		rm -f /etc/systemd/system/"$SERVICE"
		systemctl daemon-reload || true
	elif command -v rc-update >/dev/null 2>&1; then
		rm -f /etc/local.d/"${SERVICE}".start
		echo "OpenRC: removed /etc/local.d/${SERVICE}.start"
	fi
}

current_cu_count() {
	dmesg | grep -o 'active_cu_number [0-9]*' | tail -1 | awk '{print $2}'
}

run_verify_for_target() {
	local target="$1"
	local se sh wgp log status rc cu_count started finished

	read -r se sh wgp < <(target_to_tuple "$target")
	log="$STATEDIR/logs/wgp-${target}-se${se}-sh${sh}-wgp${wgp}.log"
	started="$(date -Iseconds)"
	cu_count="$(current_cu_count || true)"
	status="PASS"
	rc=0

	echo "Testing target index=$target SE$se SH$sh WGP$wgp..."
	set +e
	if command -v timeout >/dev/null 2>&1; then
		timeout "$TIMEOUT" "$VERIFY" --elements "$ELEMENTS" --passes "$PASSES" --iters "$ITERS" 2>&1 | tee "$log"
		rc=${PIPESTATUS[0]}
		# timeout: 124=timed out, 137=SIGKILL, 143=SIGTERM
		if [ "$rc" -eq 0 ]; then
			status="PASS"
		elif [ "$rc" -eq 124 ] || [ "$rc" -eq 137 ] || [ "$rc" -eq 143 ]; then
			echo "VERIFIER HUNG: GPU unresponsive after ${TIMEOUT}s — marking WGP $target as HUNG." | tee -a "$log"
			status="HUNG"
		else
			status="FAIL"
		fi
	else
		"$VERIFY" --elements "$ELEMENTS" --passes "$PASSES" --iters "$ITERS" 2>&1 | tee "$log"
		rc=${PIPESTATUS[0]}
		[ "$rc" -eq 0 ] || status="FAIL"
	fi
	set -e
	finished="$(date -Iseconds)"

	printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' \
		"$target" "$se" "$sh" "$wgp" "$status" "$rc" \
		"${cu_count:-unknown}" "$started" "$finished" >>"$STATEDIR/results.tsv"
}

next_reboot() {
	local target="$1"
	local se sh wgp

	read -r se sh wgp < <(target_to_tuple "$target")
	if is_alpine_grub; then
		# Alpine with GRUB: edit kernel cmdline for next target's isolation.
		# No initramfs rebuild — kernel reads disable_cu at boot.
		grub_set_disable_cu "$(disable_cu_for_target "$target")"
	elif is_alpine; then
		# Alpine without GRUB: config was already restored to 40 CUs in resume.
		:
	else
		# Other distros: bake isolation config into initramfs.
		write_config_for_target "$target"
		refresh_initramfs
	fi
	# Write state AFTER grub edit so state and config stay in sync
	# even if power is lost mid-operation.
	echo "$target" >"$STATEDIR/current_target"
	echo "Next target: index=$target SE$se SH$sh WGP$wgp."
	echo "Rebooting in $REBOOT_DELAY seconds..."
	sleep "$REBOOT_DELAY"
	reboot
}

finish_test() {
	write_full_config
	# Alpine with GRUB: restore original grub.cfg (remove CU isolation params)
	if is_alpine_grub; then
		grub_restore
	fi
	refresh_initramfs
	remove_service
	echo "done" >"$STATEDIR/phase"
	echo "Per-WGP health test complete."
	echo "Results: $STATEDIR/results.tsv"
	awk -F'\t' 'BEGIN{pass=0; fail=0} NR>1 && $5=="PASS"{pass++} NR>1 && $5!="PASS"{fail++} END{printf "PASS WGPs: %d  FAIL/HUNG/SKIP WGPs: %d  usable CUs: %d/40\n", pass, fail, 40 - fail * 2}' "$STATEDIR/results.tsv"
	if [ "$FINAL_REBOOT" = "1" ]; then
		echo "Rebooting in $REBOOT_DELAY seconds to reload amdgpu with the restored full-40CU config..."
		sleep "$REBOOT_DELAY"
		reboot
	else
		echo "Full 40-CU config is written for the next boot; current boot remains on the last isolated WGP."
	fi
}

# run_direct — test all 20 WGPs in a single session via hot-reload.
# Used by the 'direct' command. Isolation failures are handled gracefully:
# if a WGP cannot be isolated, it is skipped and 40 CUs are restored
# before moving on (or aborting if even restore fails).
run_direct() {
	local script_dir passed=0 failed=0 target se sh wgp last_status last_cu
	script_dir="$(dirname "$(readlink -f "$0")")"

	write_full_config
	echo "=== BC-250 Direct WGP Health Test ==="
	echo "Testing all 20 WGPs in one session via hot-reload."
	echo "Results: $STATEDIR/results.tsv"
	echo ""

	for target in {0..19}; do
		read -r se sh wgp < <(target_to_tuple "$target")
		# Apply isolation and reload; if it fails, restore 40 CUs and skip this WGP
		write_config_for_target "$target"
		if ! hot_reload_amdgpu "WGP $target isolation (SE$se SH$sh WGP$wgp)" "$(disable_cu_for_target "$target")"; then
			echo "WARNING: Skipping WGP $target — isolation failed, marking as UNTESTABLE." >&2
			printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' \
				"$target" "$se" "$sh" "$wgp" "SKIP" "-1" \
				"$(current_cu_count || echo unknown)" "$(date -Iseconds)" "$(date -Iseconds)" \
				>>"$STATEDIR/results.tsv"
			failed=$((failed + 1))
			# Try to restore 40 CUs before continuing
			write_full_config
			hot_reload_amdgpu "40 CU restore (recovery)" "" || {
				echo "FATAL: Cannot even restore 40 CUs. Aborting." >&2
				exit 1
			}
			echo "Progress: WGP $((target + 1))/20 complete | passed=$passed failed=$failed | last: SE$se SH$sh WGP$wgp = SKIP"
			echo ""
			continue
		fi
		# Run test
		run_verify_for_target "$target"
		# Count result
		last_status=$(tail -1 "$STATEDIR/results.tsv" | awk -F'\t' '{print $5}')
		last_cu=$(tail -1 "$STATEDIR/results.tsv" | awk -F'\t' '{print $7}')
		if [ "$last_status" = "PASS" ]; then
			passed=$((passed + 1))
		else
			failed=$((failed + 1))
		fi
		# Restore 40 CUs after each test (clean state for next isolation)
		write_full_config
		hot_reload_amdgpu "40 CU restore" "" || {
			echo "FATAL: Cannot restore 40 CUs. Aborting." >&2
			exit 1
		}
		# Show progress
		echo "Progress: WGP $((target + 1))/20 complete | passed=$passed failed=$failed | last: SE$se SH$sh WGP$wgp = $last_status (CUs=$last_cu)"
		echo ""
	done

	# Final 40 CU restore (already done after last WGP, but ensure it)
	write_full_config
	hot_reload_amdgpu "40 CU restore (final)" "" || true

	# Try to restart any GPU services that were killed during hot-reloads
	rc-service cyan-skillfish-governor-smu restart 2>/dev/null || \
		echo "Note: GPU governor was killed during testing. Reboot to restore all services."

	# Print final summary
	echo "=== Direct health test complete ==="
	echo "Results: $STATEDIR/results.tsv"
	echo "PASS WGPs: $passed  FAIL WGPs: $failed  usable CUs: $((40 - failed * 2))/40"
	if [ "$failed" -gt 0 ]; then
		echo ""
		echo "To generate a CU mask excluding bad WGPs:"
		echo "  sudo $script_dir/bc250-cu-mask.sh --results $STATEDIR/results.tsv --install"
	fi
}

cmd="${1:-}"
case "$cmd" in
	direct)
		need_root
		if is_alpine; then
			echo "WARNING: Alpine detected. hot-reload (modprobe -r amdgpu) may freeze the kernel" >&2
			echo "on BC-250 GPUs. If the system hangs, use 'start' instead (reboot-based, GRUB cmdline)." >&2
			echo "" >&2
		fi
		[ -x "$VERIFY" ] || die "verifier not executable: $VERIFY"
		mkdir -p "$STATEDIR/logs"
		cat >"$STATEDIR/results.tsv" <<'EOF'
#idx	se	sh	wgp	status	rc	active_cu	started	finished
EOF
		run_direct
		;;
	start)
		need_root
		[ -x "$VERIFY" ] || die "verifier not executable: $VERIFY"
		mkdir -p "$STATEDIR/logs"
		cat >"$STATEDIR/results.tsv" <<'EOF'
#idx	se	sh	wgp	status	rc	active_cu	started	finished
EOF
		echo "running" >"$STATEDIR/phase"
		# Ensure clean 40-CU config on disk before first reboot
		write_full_config
		# Alpine with GRUB: inject isolation via kernel cmdline (no hot-reload, no mkinitfs)
		if is_alpine_grub; then
			grub_init_cmdline
			# disable_cu for target 0 is set by next_reboot below
		fi
		install_service
		next_reboot 0
		;;
	resume)
		need_root
		[ -x "$VERIFY" ] || die "verifier not executable: $VERIFY"
		mkdir -p "$STATEDIR/logs"
		phase="$(cat "$STATEDIR/phase" 2>/dev/null || echo missing)"
		[ "$phase" = "running" ] || die "health test is not running (phase=$phase)"
		target="$(cat "$STATEDIR/current_target" 2>/dev/null || echo 0)"
		# Alpine with GRUB: kernel already booted with isolation from cmdline.
		# No hot-reload needed — just verify the already-isolated GPU.
	if is_alpine_grub; then
		cu="$(current_cu_count || echo 0)"
		[ "$cu" = "2" ] || echo "WARNING: expected 2 CUs from GRUB cmdline, got $cu — isolation may have failed" >&2
		elif is_alpine; then
			# Alpine without GRUB: apply isolation via hot-reload (may hang on some GPUs)
			write_config_for_target "$target"
			hot_reload_amdgpu "WGP $target isolation" "$(disable_cu_for_target "$target")" || {
				echo "WARNING: hot-reload failed. Test may run with wrong CU config." >&2
			}
		fi
		run_verify_for_target "$target"
		next=$((target + 1))
		if [ "$next" -lt 20 ]; then
			next_reboot "$next"
		else
			finish_test
		fi
		;;
	quick)
		[ -x "$VERIFY" ] || die "verifier not executable: $VERIFY"
		"$VERIFY" --elements "$ELEMENTS" --passes "$PASSES" --iters "$ITERS"
		;;
	status)
		if [ -f "$STATEDIR/results.tsv" ]; then
			cat "$STATEDIR/results.tsv"
		else
			echo "No health-test results in $STATEDIR"
		fi
		;;
	reset)
		need_root
		remove_service
		rm -rf "$STATEDIR"
		rm -f "$CONF"
		# Alpine with GRUB: restore original grub.cfg
		if is_alpine_grub; then
			grub_restore
		fi
		refresh_initramfs
		echo "Removed health-test state, service, resume script, isolation config, and GRUB marker."
		;;
	-h|--help|"")
		usage
		;;
	*)
		die "unknown command: $cmd"
		;;
esac
